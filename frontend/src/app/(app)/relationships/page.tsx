"use client";

import { useCallback, useEffect, useMemo, useState } from "react";
import { FindingList } from "@/components/finding-list";
import { ListSkeleton, LoadingLabel, Skeleton } from "@/components/loading";
import {
  Button,
  Card,
  ErrorNote,
  NoDataset,
  PageHeader,
  SyntheticBanner,
} from "@/components/ui";
import { api, label } from "@/lib/api";
import type { Finding, Goals } from "@/lib/types";
import { useWorkspace } from "@/lib/workspace";

export default function DiscoverPage() {
  const { dataset } = useWorkspace();
  const datasetId = dataset?.dataset_id;
  const [goals, setGoals] = useState<Goals | null>(null);
  const [goalId, setGoalId] = useState("open");
  const [conditions, setConditions] = useState<Set<string>>(new Set());
  const [splitBy, setSplitBy] = useState<string>("");
  const [findings, setFindings] = useState<Finding[] | null>(null);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [show, setShow] = useState<Record<string, boolean>>({});

  // goals and conditions are generated by the backend from this dataset's columns
  useEffect(() => {
    if (!datasetId) return;
    api
      .goals(datasetId)
      .then((g) => {
        setGoals(g);
        setConditions(new Set(g.conditions.mapped));
        const wanted = new URLSearchParams(window.location.search).get("goal");
        setGoalId(
          wanted && g.goals.some((x) => x.id === wanted) ? wanted : "open",
        );
      })
      .catch((e) => setError(e.message));
  }, [datasetId]);

  const load = useCallback(async () => {
    if (!datasetId) return;
    try {
      setFindings(await api.findings({ dataset_id: datasetId }));
    } catch (e) {
      setError((e as Error).message);
    }
  }, [datasetId]);

  useEffect(() => {
    // eslint-disable-next-line react-hooks/set-state-in-effect -- fetch on dataset change
    load();
  }, [load]);

  const goal = goals?.goals.find((g) => g.id === goalId);

  async function discover() {
    if (!datasetId || !goal || !goals) return;
    setBusy(true);
    setError(null);
    try {
      const chosen = [...conditions];
      await api.discover(datasetId, {
        goal: goal.question,
        outcomes: goal.outcomes.length ? goal.outcomes : undefined,
        extra_outcomes: goal.extra_outcomes,
        conditions: chosen,
        split_by: splitBy || undefined,
        extra_conditions: chosen.filter((c) =>
          goals.conditions.unmapped.includes(c),
        ),
      });
      await load();
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setBusy(false);
    }
  }

  const groups = useMemo(() => {
    const list = findings ?? [];
    return {
      validated: list.filter((f) => f.status === "validated"),
      candidate: list.filter((f) => f.status === "candidate"),
      rejected: list.filter((f) => f.status === "rejected"),
      none: list.filter((f) => f.status === "not_significant"),
    };
  }, [findings]);
  const lastGoal = findings?.[0]?.goal;

  if (!dataset) return <NoDataset />;

  const toggle = (c: string) =>
    setConditions((s) => {
      const next = new Set(s);
      if (next.has(c)) next.delete(c);
      else next.add(c);
      return next;
    });

  return (
    <>
      <PageHeader eyebrow="Discover" title="Discovery">
        Choose a goal, or explore openly. Every association is first looked for
        on 70% of the experiments, then re-tested on the 30% the engine never
        saw and against random shuffles. The goals below are generated from this
        dataset&apos;s columns; they are not fixed.
      </PageHeader>
      {dataset.synthetic && <SyntheticBanner />}

      <Card title="1 · Discovery goal">
        {!goals ? (
          <div className="grid gap-2 sm:grid-cols-2" aria-busy="true">
            {Array.from({ length: 4 }, (_, i) => (
              <Skeleton key={i} className="h-16" />
            ))}
          </div>
        ) : (
          <div className="grid gap-2 sm:grid-cols-2" role="radiogroup">
            {goals.goals.map((g) => (
              <label
                key={g.id}
                className={`flex cursor-pointer gap-3 rounded-lg border p-3 text-sm transition ${g.id === goalId ? "border-accent bg-surface-2" : "border-line hover:border-ink-2"}`}
              >
                <input
                  type="radio"
                  name="goal"
                  className="mt-1 accent-[var(--accent)]"
                  checked={g.id === goalId}
                  onChange={() => setGoalId(g.id)}
                />
                <span>
                  <span className="block font-medium text-ink">
                    {g.question}
                  </span>
                  <span className="mt-0.5 block text-xs text-muted">
                    {g.kind === "open"
                      ? g.description
                      : g.kind === "unmapped"
                        ? "Column from the file, not in the standard schema"
                        : g.description || "Outcome variable"}
                  </span>
                </span>
              </label>
            ))}
          </div>
        )}
      </Card>

      <Card title="2 · Conditions to examine" className="mt-4">
        {!goals ? (
          <Skeleton className="h-6 w-2/3" />
        ) : (
          <div className="space-y-3 text-sm">
            <div className="flex flex-wrap gap-2">
              {goals.conditions.mapped.map((c) => (
                <Chip key={c} on={conditions.has(c)} onClick={() => toggle(c)}>
                  {label(c)}
                </Chip>
              ))}
            </div>
            {goals.conditions.unmapped.length > 0 && (
              <div>
                <p className="mb-1.5 text-xs text-muted">
                  Other columns in the file (not in the standard schema).
                  Include them as conditions if they describe the experiment
                  setup:
                </p>
                <div className="flex flex-wrap gap-2">
                  {goals.conditions.unmapped
                    .filter((c) => !goal?.extra_outcomes.includes(c))
                    .map((c) => (
                      <Chip
                        key={c}
                        on={conditions.has(c)}
                        onClick={() => toggle(c)}
                      >
                        {label(c)}
                      </Chip>
                    ))}
                </div>
              </div>
            )}
          </div>
        )}
        {goals && goals.split_options.length > 0 && (
          <label className="mt-5 block text-sm">
            <span className="mb-1 block text-xs text-muted">
              Keep together when splitting discovery / unseen data (choose a
              coarser group if experiments in it are not independent, so nothing
              leaks between the parts):
            </span>
            <select
              value={splitBy}
              onChange={(e) => setSplitBy(e.target.value)}
              disabled={goals.split_options.length < 2}
              aria-label="Keep together when splitting"
              className="rounded-md border border-line bg-surface px-2 py-1.5"
            >
              {goals.split_options.map((o, i) => (
                <option key={o.column} value={i === 0 ? "" : o.column}>
                  {o.label} · {o.groups} groups
                </option>
              ))}
            </select>
          </label>
        )}
        <div className="mt-5 flex flex-wrap items-center gap-3">
          <Button
            onClick={discover}
            disabled={busy || !goal || conditions.size === 0}
          >
            {busy ? "Analyzing…" : "Run discovery"}
          </Button>
          <span className="text-xs text-muted">
            data → statistical analysis → findings → validation on unseen data →
            evidence
          </span>
        </div>
      </Card>

      <div className="mt-4">{error && <ErrorNote message={error} />}</div>

      <div className="mt-6">
        {busy ? (
          <Card title="Running discovery">
            <div className="space-y-4" aria-busy="true">
              <LoadingLabel>
                Testing each condition against the goal on the discovery split,
                then validating on held-out experiments, random shuffles and
                bootstrap resamples, and checking third variables…
              </LoadingLabel>
              <ListSkeleton rows={5} />
            </div>
          </Card>
        ) : findings === null ? (
          <Card title={<Skeleton className="h-4 w-48" />}>
            <ListSkeleton rows={3} />
          </Card>
        ) : findings.length === 0 ? (
          <Card>
            <p className="text-sm text-ink-2">
              No discovery run yet for this dataset. Choose a goal and run
              discovery.
            </p>
          </Card>
        ) : (
          <div className="fade-in space-y-4">
            <p className="text-sm text-ink-2">
              Last run: <span className="font-medium text-ink">{lastGoal}</span>{" "}
              · {findings.length} associations tested
            </p>
            <Section
              title="Validated findings"
              count={groups.validated.length}
              note="Observed in the discovery data and confirmed on unseen experiments. Statistical associations, not causal or scientific conclusions."
            >
              <FindingList findings={groups.validated} />
            </Section>
            {groups.candidate.length > 0 && (
              <Section
                title="Candidates"
                count={groups.candidate.length}
                note="Observed in the discovery data, but validation was inconclusive."
              >
                <FindingList findings={groups.candidate} reason />
              </Section>
            )}
            <Section
              title="Rejected"
              count={groups.rejected.length}
              note="An initial signal was observed, but it failed validation: likely chance patterns."
              collapsed={!show.rejected}
              onToggle={() => setShow((s) => ({ ...s, rejected: !s.rejected }))}
            >
              <FindingList findings={groups.rejected} reason />
            </Section>
            <Section
              title="No supported relationship found"
              count={groups.none.length}
              note="With this analysis and this data, no supported relationship was found. That does not show these variables have no effect: a relationship could be non-monotonic, depend on another variable, or need more data or a different method."
              collapsed={!show.none}
              onToggle={() => setShow((s) => ({ ...s, none: !s.none }))}
            >
              <FindingList findings={groups.none} reason />
            </Section>
          </div>
        )}
      </div>
    </>
  );
}

function Chip({
  on,
  onClick,
  children,
}: {
  on: boolean;
  onClick: () => void;
  children: React.ReactNode;
}) {
  return (
    <button
      type="button"
      aria-pressed={on}
      onClick={onClick}
      className={`rounded-full border px-3 py-1 text-sm transition ${on ? "border-accent bg-surface-2 text-ink" : "border-line text-muted hover:text-ink"}`}
    >
      {on ? "✓ " : ""}
      {children}
    </button>
  );
}

function Section({
  title,
  count,
  note,
  collapsed,
  onToggle,
  children,
}: {
  title: string;
  count: number;
  note: string;
  collapsed?: boolean;
  onToggle?: () => void;
  children: React.ReactNode;
}) {
  return (
    <Card
      title={`${title} (${count})`}
      action={
        onToggle && count > 0 ? (
          <Button variant="ghost" onClick={onToggle}>
            {collapsed ? "Show" : "Hide"}
          </Button>
        ) : undefined
      }
    >
      <p className="mb-3 text-xs text-muted">{note}</p>
      {!collapsed && children}
    </Card>
  );
}
