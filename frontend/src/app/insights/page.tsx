"use client";

import Link from "next/link";
import { useEffect, useState } from "react";
import { FindingList } from "@/components/finding-list";
import { Button, Card, ErrorNote, NoDataset, PageHeader, SyntheticBanner } from "@/components/ui";
import { api } from "@/lib/api";
import type { Finding } from "@/lib/types";
import { useWorkspace } from "@/lib/workspace";

export default function InsightsPage() {
  const { dataset } = useWorkspace();
  const [findings, setFindings] = useState<Finding[] | null>(null);
  const [summary, setSummary] = useState<{ summary: string; caveats: string[]; model: string } | null>(
    null,
  );
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);

  const datasetId = dataset?.dataset_id;

  useEffect(() => {
    if (!datasetId) return;
    api
      .findings({ dataset_id: datasetId, status: "validated" })
      .then((list) => {
        setFindings(list);
        setSummary(null);
      })
      .catch((e) => setError(e.message));
  }, [datasetId]);

  async function summarize() {
    if (!datasetId) return;
    setBusy(true);
    try {
      setSummary(await api.summary(datasetId));
      setError(null);
    } catch (e) {
      setError((e as Error).message);
    } finally {
      setBusy(false);
    }
  }

  if (!dataset) return <NoDataset />;

  return (
    <>
      <PageHeader eyebrow="Insights" title="Validated findings, ranked">
        Ranking combines effect strength, amount of supporting data, validation result and how
        directly the outcome relates to fire safety (extinction and ignition weigh most).
      </PageHeader>
      {dataset.synthetic && <SyntheticBanner />}
      {error && <ErrorNote message={error} />}

      {findings && findings.length === 0 ? (
        <Card>
          <p className="text-sm text-ink-2">
            No validated findings yet.{" "}
            <Link href="/relationships" className="font-medium text-accent">
              Run discovery
            </Link>{" "}
            first.
          </p>
        </Card>
      ) : (
        <div className="space-y-4">
          <Card
            title="AI summary"
            action={
              <Button onClick={summarize} disabled={busy || !findings?.length}>
                {busy ? "Summarizing…" : summary ? "Regenerate" : "Summarize"}
              </Button>
            }
          >
            {summary ? (
              <div className="space-y-2 text-sm">
                <p className="text-ink">{summary.summary}</p>
                <ul className="list-disc pl-5 text-xs text-ink-2">
                  {summary.caveats.map((c) => (
                    <li key={c}>{c}</li>
                  ))}
                </ul>
                <p className="text-xs text-muted">Generated by {summary.model} from the ranked list below.</p>
              </div>
            ) : (
              <p className="text-sm text-ink-2">
                A plain-language overview of the top findings, written only from their statistics.
              </p>
            )}
          </Card>
          <Card title="Ranking">
            <FindingList findings={findings ?? []} />
          </Card>
        </div>
      )}
    </>
  );
}
